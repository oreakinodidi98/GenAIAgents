"""Demo: ChatOpenAI + LangChain agent with tool calling.

This script shows how to:
1. Load configuration from environment variables.
2. Create and stream responses from a ChatOpenAI model.
3. Register tools and run a simple LangChain agent.
"""

# This is a demo script to show how to use the ChatOpenAI model from
# langchain_openai and create a simple agent using LangChain.


from langchain_openai import ChatOpenAI
# Use to create an agent from LangChain.
from langchain.agents import create_agent
from langchain_core.messages import HumanMessage
# Use to define tools.
from langchain_core.tools import tool
# Use to connect to Multi-Server MCP (Managed Chat Platform) for agent orchestration.
from langchain_mcp_adapters.client import MultiServerMCPClient
# Using interceptors to wrap tool execution with retry logic and fallback values,
# making the agent more resilient.
from langchain_mcp_adapters.interceptors import MCPToolCallRequest

import httpx
from markdownify import markdownify

import json
import os
import asyncio
from dotenv import load_dotenv
from pydantic import SecretStr

# Load environment variables from the .env file.
load_dotenv()

# Function to test if environment variables are set.
def require_env(name: str) -> str:
    """Return a required environment variable or fail fast with a clear message."""
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing required environment variable: {name}")
    return value

# Retrieve required environment variables.
llm_model_deployment_name = require_env('LLM_MODEL_DEPLOYMENT_NAME_CHATGPT')
foundry_api_key = require_env('FOUNDRY_API_KEY')
foundry_endpoint = require_env('FOUNDRY_ENDPOINT')

# Note: The following environment variables are used to connect to the Microsoft Learn MCP server.
aca_mcp_server_open_web_search_fqdn = require_env("ACA_MCP_SERVER_OPEN_WEB_SEARCH_FQDN")
app_service_mcp_server_open_web_search_fqdn = require_env("APP_SERVICE_MCP_SERVER_OPEN_WEB_SEARCH_FQDN")

# Create a ChatOpenAI model instance with streaming enabled.
model = ChatOpenAI(
    base_url=f"{foundry_endpoint}/openai/v1",
    api_key=SecretStr(foundry_api_key),
    model=llm_model_deployment_name,
    streaming=True,  # Stream output as it is generated by the model.
    max_completion_tokens=512  # Set response token limit to 512.
)

# Use a separate non-streaming model for the agent itself to reduce malformed
# partial tool-call output during long multi-step research tasks.
agent_model = ChatOpenAI(
    base_url=f"{foundry_endpoint}/openai/v1",
    api_key=SecretStr(foundry_api_key),
    model=llm_model_deployment_name,
    streaming=False,
    max_completion_tokens=1024,
)

# Invoke model with a test prompt and stream the output.
prompt = "Hi there!"
response = model.stream([HumanMessage(content=prompt)])

# Print the streamed response.
for chunk in response:
    print(chunk.content, end="", flush=True)

# Test the agent with a simple question that requires reasoning and tool usage.
question = (
    "What are the latest open and closed-source LLM models in 2026?\n"
    "Compare their capabilities and limitations.\n"
    "Search the web sequentially, inspect a reasonable number of high-quality sources, and fetch relevant webpages.\n"
    "Do not issue a tool call unless you have valid arguments for it.\n"
    "Cite your references at the end of the response."
)
# question = "How do i deploy a Langchai agent into Microsoft Foundary"
# question = "What is 7 multiplied by 13?"

# retry if the request fails
async def retry_interceptor(
    request: MCPToolCallRequest,
    handler,
    max_retries: int = 3,
    delay: float = 1.0,
):
    """Retry failed tool calls with exponential backoff."""
    last_error = None
    for attempt in range(max_retries):
        try:
            return await handler(request)
        except Exception as e:
            last_error = e
            if attempt < max_retries - 1:
                wait_time = delay * (2 ** attempt)  # Exponential backoff
                print(f"Tool {request.name} failed (attempt {attempt + 1}), retrying in {wait_time}s...")
                await asyncio.sleep(wait_time)
    raise last_error

# fallback interceptor to return a fallback value if tool execution fails
async def fallback_interceptor(
    request: MCPToolCallRequest,
    handler,
):
    """Return a fallback value if tool execution fails."""
    try:
        return await handler(request)
    except TimeoutError:
        return f"Tool {request.name} timed out. Please try again later."
    except ConnectionError:
        return f"Could not connect to {request.name} service. Using cached data."

# Connect to the MCP server by creating an MCP client
# Use MultiServerMCPClient to connect to the MCP server over Streamable HTTP transport
# Client automatically discovers all tools the server exposes and makes them available as LangChain tools
mcp_client = MultiServerMCPClient(
    {
        "web-search": {
            "url": f"https://{app_service_mcp_server_open_web_search_fqdn}/mcp",
            # "url": f"https://{aca_mcp_server_open_web_search_fqdn}/mcp",
            "transport": "http",
        }
    },
    # registering the retry_interceptor and fallback_interceptor so every tool call is automatically protected.
    tool_interceptors=[retry_interceptor, fallback_interceptor]
)

# Define a local @tool that fetches a webpage and converts its HTML to markdown.
@tool
def fetch_webpage_content(url: str, timeout: float = 10.0) -> str:
    """Fetch webpage and convert HTML to markdown."""
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
    }
    try:
        response = httpx.get(url, headers=headers, timeout=timeout)
        response.raise_for_status()
    
        return markdownify(response.text)
    except Exception as e:
        return f"Error fetching {url}: {e!s}"

# Stream agent execution asynchronously and print the latest agent response.
async def run_agent() -> None:
    # Discover tools exposed (async call must be inside async function).
    mcp_tools_web_search = await mcp_client.get_tools()
    print("MCP tools Discovered:", [t.name for t in mcp_tools_web_search])

    # Find the tool called "search" by name
    search_tool = next(t for t in mcp_tools_web_search if t.name == "search")
    
    # Calling Search tool directly to verify the connection works
    # invoke the search tool and inspect the raw result returned by the MCP server
    result = await search_tool.ainvoke(
    {
        "query": "What are the latest LLM models?", 
        "limit": 20, 
        "engines": ["duckduckgo"]
    })

    # result is already a list — extract the "text" field and parse it
    data = json.loads(result[0]["text"])
    print(json.dumps(data, indent=4))

    # Create an agent with the remote search tool and the local fetch_webpage_content tool.
    # The agent will reason about when to search the web, fetch pages, and synthesize a final answer with citations.
    agent_tools = [search_tool, fetch_webpage_content]
    agent_with_mcp = create_agent(
        model=agent_model.bind_tools(agent_tools, parallel_tool_calls=False),
        tools=agent_tools
    )

    last_message = None

    async for step in agent_with_mcp.astream(
        {"messages": [HumanMessage(content=question)]},
        stream_mode="values"
    ):
        # Output has two sections: the human message and the agent response.
        # Print the latest message, which is the agent response.
        step["messages"][-1].pretty_print()
        last_message = step["messages"][-1]

    # Print the final response content as plain text for terminal runs.
    content = getattr(last_message, "content", "")
    if isinstance(content, list):
        markdown_text = "\n".join(
            part.get("text", "") if isinstance(part, dict) else str(part)
            for part in content
        )
    else:
        markdown_text = str(content)

    print("\nFinal response:\n")
    print(markdown_text)


if __name__ == "__main__":
    asyncio.run(run_agent())